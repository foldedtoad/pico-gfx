# Run:  mpremote run raw_spi_test.py

import time
from machine import Pin, SPI

# ---------------- wiring (edit to YOUR pins) ----------------
SPI_ID = 0
SCK, MOSI, MISO = 6, 7, 16      # MISO unused by display; GP16 must be free
CS, DC, RST, BL = 12, 11, 10, 13
FREQ = 10_000_000
# -------------------------------------------------------------

spi = SPI(SPI_ID, baudrate=FREQ, polarity=0, phase=0, sck=SCK, mosi=MOSI, miso=MISO)
cs  = Pin(CS,  Pin.OUT, value=1)
dc  = Pin(DC,  Pin.OUT, value=0)
rst = Pin(RST, Pin.OUT, value=1)
bl  = Pin(BL,  Pin.OUT, value=0)

def cmd(c, data=None):
    cs(0)
    dc(0); spi.write(bytes([c]))
    if data:
        dc(1); spi.write(bytes(data))
    cs(1)


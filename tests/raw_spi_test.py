def fill(rgb565):
    cmd(0x2A, [0, 0, 0, 239])
    cmd(0x2B, [0, 0, 0, 239])
    row = bytes([rgb565 >> 8, rgb565 & 0xFF]) * 240
    cs(0)
    dc(0); spi.write(b'\x2C')
    dc(1)
    for _ in range(240):
        spi.write(row)
    cs(1)

print("reset")
rst(1); time.sleep_ms(10); rst(0); time.sleep_ms(50); rst(1); time.sleep_ms(150)

print("init")
for c, d in INIT:
    cmd(c, d)
cmd(0x11); time.sleep_ms(120)       # sleep out
cmd(0x29); time.sleep_ms(20)        # display on
bl(1)

for name, colour in (("RED", 0xF800), ("GREEN", 0x07E0), ("BLUE", 0x001F), ("WHITE", 0xFFFF)):
    print("fill", name)
    fill(colour)
    time.sleep(1.5)

print("done - screen should be white")
